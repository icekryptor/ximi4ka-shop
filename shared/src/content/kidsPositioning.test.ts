import { describe, expect, it } from 'vitest'
import { AGE_FORMULA, findKidsPositioning } from './kidsPositioning'

const flagged = (text: string, field: 'body' | 'meta' = 'body') =>
  findKidsPositioning(text, field).length > 0

describe('findKidsPositioning: ловит детское позиционирование', () => {
  it.each([
    'Химические наборы для детей и подростков.',
    'Химичка — наборы для химических опытов для детей',
    'Можно проводить дома вместе с детьми.',
    'Безопасны ли наборы для детей?',
    'детский праздник',
  ])('прямое «для детей»: %s', (text) => {
    expect(flagged(text)).toBe(true)
  })

  it.each(['ребёнок смешивает реактивы', 'ваш ребенок сможет', 'Ребята!', 'для малышей'])(
    'ребёнок и обращения: %s',
    (text) => {
      expect(flagged(text)).toBe(true)
    },
  )

  it.each([
    'от 10 лет',
    'подарок · от 8 лет',
    'для детей и подростков 10–18 лет',
    'Возраст 8+',
    'маркировка 12+',
    'опыты для 1–4 классов',
    'опыты в начальной школе',
  ])('возраст младше 14: %s', (text) => {
    expect(flagged(text)).toBe(true)
  })

  it.each([
    'работайте вместе со взрослыми',
    'До 14 лет под присмотром взрослых.',
    'обратитесь за помощью к взрослым или к врачу',
    'только в присутствии взрослых',
    'со взрослым рядом',
  ])('взрослые вне формулы возраста: %s', (text) => {
    expect(flagged(text)).toBe(true)
  })

  it.each([
    'Что говорят родители',
    'подарок для родителей школьника',
    'Сын в восторге от набора',
    'Дочь (11 лет) делает эксперименты сама',
    'Более 1000 довольных семей',
    'как девочке, так и мальчику',
  ])('родители и семья: %s', (text) => {
    expect(flagged(text)).toBe(true)
  })

  it.each([
    'В каталоге собраны наборы для разных возрастов',
    'подберём набор под интересы и возраст',
    'Подберите набор по возрасту',
    'соответствуют возрастным маркировкам',
    'развивающий набор',
    'на каникулах',
    'отличная игрушка',
    'образ юного учёного',
  ])('прочее: %s', (text) => {
    expect(flagged(text)).toBe(true)
  })

  it.each([
    'с 8 лет',
    'старше 8 лет',
    'от 10 до 14 лет',
    'до 14 лет',
    'набор для детишек',
    'работайте ко взрослым поближе',
    'с помощью взрослых',
    'подарок родителю',
    'для дочери',
    'набор на всю семью',
    'с мамой или папой',
  ])('найдено ревью: %s', (text) => {
    expect(flagged(text)).toBe(true)
  })

  it('называет правило и найденный фрагмент', () => {
    expect(findKidsPositioning('Химические наборы для детей.')).toEqual([
      { rule: 'дети', match: 'детей', index: 22 },
    ])
  })
})

describe('findKidsPositioning: не трогает допустимое', () => {
  it.each([
    'Храните в месте, недоступном для детей.',
    'Реактивы храните в месте, недоступном для маленьких детей.',
    'храните вне досягаемости детей и животных',
    'Химические реактивы — не игрушки.',
    'Даже разбавленная серная кислота — не игрушка.',
  ])('предупреждения о хранении: %s', (text) => {
    expect(flagged(text)).toBe(false)
  })

  it.each([
    '110+ реакций',
    '161 опыт',
    '14+',
    'с 14 лет',
    'для подростков с 14 лет и взрослых',
    'подарок подростку с 14 лет или взрослому',
    'программа 9–11 класс',
    'семь опытов',
    'детальная инструкция',
    'Родительская категория',
    'родительный падеж',
    'С какого возраста можно работать с набором самостоятельно?',
  ])('нейтральное: %s', (text) => {
    expect(flagged(text)).toBe(false)
  })

  it.each([
    'Беречь от детей.',
    'Хранить вдали от детей.',
    'Хранить в не доступном для детей месте.',
    'Набор не является игрушкой.',
    'Не является детской игрушкой.',
  ])('другие формы предупреждений: %s', (text) => {
    expect(flagged(text)).toBe(false)
  })

  it.each([
    'мерная колба, 2 класс точности',
    '3 класс опасности',
    'Срок годности от 2 лет',
    'Гарантия от 1 года',
    'CuSO4 + 2NaOH',
    'Купите 2 + 1',
    'гребенка для пробирок',
    'Работ 5 лет',
  ])('технические формулировки: %s', (text) => {
    expect(flagged(text)).toBe(false)
  })

  it('формула возраста, перенесённая на новую строку, с коротким тире и без точки', () => {
    const wrapped = AGE_FORMULA.replace('со взрослыми', 'со\n  взрослыми')
      .replace('—', '–')
      .slice(0, -1)
    expect(flagged(wrapped)).toBe(false)
  })

  it('формула возраста целиком', () => {
    expect(flagged(`Возраст. ${AGE_FORMULA} Работайте в очках.`)).toBe(false)
  })

  it('формула с неразрывными пробелами', () => {
    expect(flagged(AGE_FORMULA.replace(/ /g, ' '))).toBe(false)
  })
})

describe('findKidsPositioning: «набор юного химика» (решение Р3)', () => {
  it('в тексте страницы разрешён', () => {
    expect(flagged('Если вы ищете набор юного химика, начните отсюда.')).toBe(false)
  })

  it('в title, description и H1 запрещён', () => {
    expect(flagged('Химичка 3.0 | Набор юного химика', 'meta')).toBe(true)
  })
})
