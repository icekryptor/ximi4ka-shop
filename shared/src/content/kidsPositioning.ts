// Позиционирование магазина — только 14+ (решение владельца от 22.10.2026, план
// docs/superpowers/plans/2026-10-22-reposition-14-plus.md). Модуль ищет в тексте
// формулировки, которые делают товар «детским»: прямые «для детей», возраст младше 14,
// «вместе со взрослыми» вне формулы возраста, родителей и семью. Предупреждения о
// хранении («недоступном для детей», «не игрушка») — обязательная безопасность, их не ловим.
//
// Модуль без runtime-импортов: его берут тесты web и api (см. память о shared и Turbopack).
// Регулярки с lookbehind — для Node; в клиентский код модуль не подключать (старый Safari).

/** Единственная допустимая формулировка возраста (решение Р1). */
export const AGE_FORMULA =
  'Для самостоятельного применения с 14 лет. Младше 14 лет — только вместе со взрослыми.'

/** body — текст страницы; meta — metaTitle, metaDescription и H1. */
export type KidsPositioningField = 'body' | 'meta'

export interface KidsPositioningHit {
  rule: string
  match: string
  index: number
}

const L = '[а-яё]' // буква слова: границы \b в JS не работают с кириллицей
const UNDER_14 = '(?:[1-9]|1[0-3])'

const re = (parts: string[]) => new RegExp(parts.join('|'), 'giu')

const RULES: { rule: string; re: RegExp }[] = [
  {
    rule: 'дети',
    re: re([`(?<!${L})дет(?:и|ей|ям|ях|ьми|ск${L}*|ств${L}*|сад${L}*|иш${L}*|вор${L}*)(?!${L})`]),
  },
  { rule: 'ребёнок', re: re([`(?<!${L})(?:ребён|ребен|ребят|малыш)`]) },
  { rule: 'игрушка', re: re(['игрушк']) },
  {
    rule: 'юный',
    re: re([
      `(?<!${L})юн(?:ый|ого|ому|ым|ых|ая|ую|ые|ом)\\s+(?:химик|исследовател|учён|учен|почвовед|натуралист)`,
    ]),
  },
  { rule: 'возраст N+', re: re([`(?<![A-Za-zА-Яа-яЁё\\d.,+])${UNDER_14}\\+(?!\\d)`]) },
  {
    rule: 'возраст младше 14',
    re: re([
      `(?<!${L})(?:от|с|старше)\\s*${UNDER_14}(?:\\s*до\\s*\\d{1,2})?\\s*(?:лет|года?)(?!${L})`,
      `(?<!${L})(?:до|младше)\\s*\\d{1,2}\\s*(?:лет|года?)(?!${L})`,
      `(?<!\\d)${UNDER_14}\\s*[–—-]\\s*\\d{1,2}\\s*лет`,
    ]),
  },
  {
    rule: 'младшие классы',
    re: re([
      `(?<![\\d–—-])[1-7]\\s*(?:[–—-]\\s*[1-9]\\s*)?класс(?!${L}*\\s+(?:точности|опасности))`,
      `начальн${L}*\\s+школ`,
      `младш${L}*\\s+(?:школ|класс)`,
    ]),
  },
  {
    rule: 'взрослые',
    re: re([
      `(?<!${L})(?:со?|ко)\\s+(?:помощью\\s+)?взросл`,
      `под\\s+(?:присмотром|наблюдением|контролем|руководством)\\s+(?:опытн${L}*\\s+)?взросл`,
      `присутстви${L}*\\s+(?:опытн${L}*\\s+)?взросл`,
      `(?<!${L})[ку]\\s+взросл`,
      `взросл${L}*\\s+рядом`,
      `позов${L}*\\s+взросл`,
    ]),
  },
  {
    rule: 'родители и семья',
    re: re([
      `(?<!${L})родител(?:и|ей|ям|ями|ях|ь|я|ю|ем|е)(?!${L})`,
      `(?<!${L})(?:мам|пап)(?:а|ы|е|у|ой|ам|ами|ах)?(?!${L})`,
      `(?<!${L})(?:сын|доч(?:ь|к|ер))`,
      `(?<!${L})сем(?:ья|ьи|ье|ьёй|ьей|ей|ьям|ьями|ьях)(?!${L})`,
      `всю\\s+семью`,
      'семейн',
      `(?<!${L})(?:мальчик|девоч)`,
    ]),
  },
  {
    rule: 'возраст',
    re: re([
      `разн${L}*\\s+возраст`,
      'по\\s+возрасту',
      `и\\s+возраст(?!${L})`,
      `возрастн${L}*\\s+маркиров`,
    ]),
  },
  { rule: 'развивающий', re: re(['развивающ']) },
  { rule: 'каникулы', re: re(['каникул']) },
]

// Формула возраста может быть перенесена на новую строку, набрана коротким тире или без
// финальной точки — маскируем её в любом таком виде.
const FORMULA_RE = new RegExp(
  AGE_FORMULA.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace(/ /g, '\\s+')
    .replace(/—/g, '[—–-]')
    .replace(/\\\.$/, '\\.?'),
  'giu',
)

// Допустимые фрагменты маскируются пробелами той же длины, чтобы индексы совпадали с исходным текстом.
const ALLOWED_ALWAYS: RegExp[] = [
  FORMULA_RE,
  re([
    `(?:не\\s*доступн${L}*|вне\\s+досягаемости)\\s+(?:для\\s+)?(?:маленьких\\s+)?дет${L}*`,
    `(?:беречь|берегите|хранить|храните|держать|держите)\\s+(?:вдали\\s+|подальше\\s+)?от\\s+(?:маленьких\\s+)?дет${L}*`,
  ]),
  re([`не\\s+(?:являет(?:ся|ются)\\s+)?(?:детск${L}*\\s+)?игрушк${L}*`]),
  // Юридический термин в политике персональных данных — не про семьи покупателей.
  re([`семейн${L}*\\s+тайн${L}*`]),
  // Сроки годности, гарантии и службы: «от 2 лет» здесь не возраст.
  re([
    `(?:срок|гаранти|годност|хранени|служб|эксплуатац)${L}*[^.!?\\n]{0,30}?(?:от|до|с)\\s*\\d{1,2}\\s*(?:лет|года?)`,
  ]),
]
const ALLOWED_IN_BODY: RegExp[] = [re([`набор${L}*\\s+юного\\s+химика`])]

const mask = (text: string, pattern: RegExp) => text.replace(pattern, (m) => ' '.repeat(m.length))

export function findKidsPositioning(
  text: string,
  field: KidsPositioningField = 'body',
): KidsPositioningHit[] {
  let t = text
  for (const pattern of ALLOWED_ALWAYS) t = mask(t, pattern)
  if (field === 'body') for (const pattern of ALLOWED_IN_BODY) t = mask(t, pattern)

  const hits: KidsPositioningHit[] = []
  for (const { rule, re: pattern } of RULES) {
    for (const m of t.matchAll(pattern)) hits.push({ rule, match: m[0], index: m.index ?? 0 })
  }
  return hits.sort((a, b) => a.index - b.index)
}
